"""Generate src/data/agentdesk.ts from the AgentDesk result files, so no number on the site is typed by hand.

Usage: python scripts/make-agentdesk-data.py <path to the agentdesk repo>
"""

import json
import re
import sys
from pathlib import Path

repo = Path(sys.argv[1])
res = repo / "eval" / "results"


def load(name: str) -> dict:
    return json.loads((res / f"{name}.json").read_text(encoding="utf-8"))


def of(text: str) -> tuple[int, int]:
    """'3 of 12' -> (3, 12)"""
    a, b = map(int, re.findall(r"\d+", text))
    return a, b


main, red, mut, abl, llm = (
    load(n) for n in ("main", "redteam", "mutants", "ablations", "llm")
)
assert mut["suite_too_weak_for"] == [], (
    "a mutant was not caught, so the red team set is too weak to quote"
)
a, b = red["path_a_compromised_model"], red["path_b_user_message"]
unsafe_main, n_main = of(main["unsafe_actions_main"])
denied_bad, denied_n = of(main["false_action_on_denied"])
conf = abl["B_confirmation_on_vs_off_main_set"]
data = {
    "commit": main["commit"],
    "date": main["date"],
    "mode": main["mode"],
    "main": {
        "n": main["n"],
        "success": main["task_success"],
        "seenOk": main["by_phrasing"]["seen"]["ok"],
        "seenN": main["by_phrasing"]["seen"]["n"],
        "heldOk": main["by_phrasing"]["held_out"]["ok"],
        "heldN": main["by_phrasing"]["held_out"]["n"],
        "toolCall": main["tool_call_accuracy"],
        "escalation": main["correct_escalation_rate"],
        "escalationRecall": main["escalation_recall"],
        "writesOnDenied": denied_bad,
        "deniedN": denied_n,
        "unsafe": unsafe_main,
        "unsafeN": n_main,
        "turns": main["turns_per_resolved"],
        "audit": main["audit_coverage"],
        "failures": len(main["failures"]),
        "failuresHeldOut": sum(
            1 for f in main["failures"] if f["phrasing"] == "held_out"
        ),
    },
    "redteam": {
        "unsafeA": a["unsafe"],
        "nA": a["n"],
        "unsafeB": b["unsafe"],
        "nB": b["n"],
        "guardrailOffUnsafe": abl["A_guardrail_on_vs_off_compromised_model"]["off"][
            "unsafe_of_60"
        ],
    },
    "mutants": {k: v["unsafe_of_60"] for k, v in mut["mutants"].items()},
    "confirmation": {
        "turnsOn": conf["on"]["turns_per_resolved"],
        "turnsOff": conf["off"]["turns_per_resolved"],
    },
    "llm": {"status": llm["status"]},
}
out = Path(__file__).resolve().parents[1] / "src" / "data" / "agentdesk.ts"
out.write_text(
    "// Generated by scripts/make-agentdesk-data.py from the AgentDesk result files. Do not edit by hand.\n"
    f"export const agentdesk = {json.dumps(data, indent=2)} as const;\n",
    encoding="utf-8",
)
print("wrote", out)
