"""Generate src/data/policylens.ts from the PolicyLens result files, so no number on the site is typed by hand.

Usage: python scripts/make-policylens-data.py <path to the policylens repo>
"""

import json
import sys
from pathlib import Path

repo = Path(sys.argv[1])
res = repo / "eval" / "results"


def load(name: str) -> dict:
    return json.loads((res / f"{name}.json").read_text(encoding="utf-8"))


names = (
    "retrieval",
    "refusal",
    "security",
    "parsing",
    "latency",
    "endtoend",
    "failures",
    "llm",
)
ret, ref, sec, par, lat, e2e, fail, llm = (load(n) for n in names)
stage = sec["filter_stage_retrieval"]
data = {
    "commit": ret["commit"],
    "date": ret["date"],
    "documents": len(
        json.loads((repo / "data" / "manifest.json").read_text(encoding="utf-8"))
    ),
    "questions": len(
        json.loads((repo / "data" / "questions.json").read_text(encoding="utf-8"))
    ),
    "retrieval": {
        "n": ret["n"],
        **{
            k: {"recall5": v["recall5"]["ALL"], "mrr": v["mrr"]["ALL"]}
            for k, v in ret["retrieval"].items()
        },
    },
    "endToEnd": {
        "n": e2e["test_answerable_n"],
        "strict": e2e["strict_correct"]["ALL"],
        "refused": e2e["refused"]["ALL"],
        "tableStrict": e2e["strict_correct"]["table"],
        "tableRefused": e2e["refused"]["table"],
    },
    "refusal": {
        k: ref["test"][k] for k in ("threshold", "precision", "recall", "over_refusal")
    },
    "security": {
        "restricted": stage["none"]["restricted_questions"],
        "noFilterLeaks": stage["none"]["questions_with_leaked_chunk"],
        "preFilterLeaks": stage["pre"]["questions_with_leaked_chunk"],
        "roleQueries": sec["role_matrix"]["queries"],
        "roleLeaks": sec["role_matrix"]["leaks"],
        "buggyCacheLeaks": sec["cache_cross_talk"][
            "leaks_with_buggy_question_only_cache"
        ],
        "cacheLeaks": sec["cache_cross_talk"]["leaks_with_isolated_cache"],
    },
    "parsing": {
        "pages": par["n"] // 2,
        "clean": par["summary"]["clean_scan"]["rapidocr_wer"],
        "hard": par["summary"]["hard_scan"]["rapidocr_wer"],
        "textLayer": par["summary"]["clean_scan"]["pymupdf_wer"],
    },
    "latency": {
        "hybridP50": lat["hybrid"]["cold_p50_ms"],
        "hybridP95": lat["hybrid"]["cold_p95_ms"],
        "rerankP50": lat["hybrid_rerank"]["cold_p50_ms"],
    },
    "llm": {
        "generator": llm["generator"],
        "judge": llm["judge"],
        "faithful": llm["judge_faithful_of_answered"],
        "judgeCorrect": llm["judge_correct_of_answered"],
        "stringMatch": llm["string_match_of_answered"],
        "agreement": llm["judge_vs_string_agreement"],
        "refusedWhenShould": llm["refused_when_should"],
        "restrictedLeaks": llm["restricted_value_leaked"],
        "restrictedN": llm["restricted_n"],
        "costPer1000": llm["cost_usd_per_1000_answers"],
        "p50": llm["latency_ms_p50"],
    },
    "errors": {
        "total": sum(b["count"] for b in fail["buckets"].values()),
        "n": fail["n"],
    },
}
out = Path(__file__).resolve().parents[1] / "src" / "data" / "policylens.ts"
out.write_text(
    "// Generated by scripts/make-policylens-data.py from the PolicyLens result files. Do not edit by hand.\n"
    f"export const policylens = {json.dumps(data, indent=2)} as const;\n",
    encoding="utf-8",
)
print("wrote", out)
